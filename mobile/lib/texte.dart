/// Sprache der App: "de" für deutschsprachige Geräte, sonst "en".
String sprache = 'de';

/// Text zum Schlüssel; {name} wird durch werte[name] ersetzt.
String tr(String key, [Map<String, Object> werte = const {}]) {
  var text = _texte[sprache]?[key] ?? _texte['de']![key] ?? key;
  werte.forEach((k, v) => text = text.replaceAll('{$k}', '$v'));
  return text;
}

/// Gratis-Rest als Text, z. B. „Noch 1 Gratis-Runde“; null = unbegrenzt, dann kein Text.
String? frei(String art, int? n) {
  if (n == null) return null;
  return tr(n == 0 ? '${art}_0' : n == 1 ? '${art}_1' : art, {'n': n});
}
